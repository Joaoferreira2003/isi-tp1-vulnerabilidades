-- ===============================================================
-- TP1 ISI — Esquema da base de dados de vulnerabilidades
-- PostgreSQL 18
--
-- Como executar:
--   a) DBeaver, contra o PostgreSQL nativo (localhost:5432)
--      -> criar primeiro a base:  CREATE DATABASE isi_tp1;
--      -> abrir este ficheiro, ligar à base isi_tp1 e executar o script todo
--   b) Automaticamente, ao subir o contentor (docker compose up -d),
--      porque a pasta sql/ está montada em /docker-entrypoint-initdb.d
--
-- As tabelas nascem VAZIAS. É o workflow KNIME que as preenche:
-- este ficheiro é o ALVO do "L" (Load) do ETL, não uma fonte de dados.
-- Desenho validado contra os dados reais — ver docs/notas.md.
-- ===============================================================

-- ---------------------------------------------------------------
-- DIMENSÕES
-- ---------------------------------------------------------------

-- Uma linha por imagem Docker analisada (6 esperadas).
-- Vem do nível de TOPO de cada JSON do Trivy (ArtifactName, Metadata, Trivy),
-- não de dentro das vulnerabilidades.
CREATE TABLE dim_imagem (
    id_imagem        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artifact_name    TEXT NOT NULL UNIQUE,   -- 'grafana/grafana:8.3.0'
    ficheiro_origem  TEXT,                   -- 'grafana.json'
    os_familia       TEXT,                   -- Metadata.OS.Family -> 'debian'
    os_versao        TEXT,                   -- Metadata.OS.Name   -> '10.9'
    image_id         TEXT,                   -- Metadata.ImageID
    tamanho_bytes    BIGINT,                 -- Metadata.Size
    data_scan        TIMESTAMPTZ,            -- CreatedAt
    trivy_versao     TEXT                    -- Trivy.Version -> '0.75.0'
);

-- Uma linha por identificador de vulnerabilidade distinto (679 esperados).
-- Apesar do nome, acomoda também GHSA/DLA/DSA: 51 das 2642 ocorrências não são
-- CVE e por isso nunca terão EPSS nem KEV. A coluna tipo_id permite filtrá-las
-- em vez de as perder silenciosamente.
--
-- O EPSS vive AQUI (e não nos factos) porque é atributo da vulnerabilidade,
-- não da ocorrência: evita repetir o mesmo score nas várias imagens onde a
-- mesma CVE aparece.
CREATE TABLE dim_cve (
    cve_id              TEXT PRIMARY KEY,    -- 'CVE-2022-28391'
    tipo_id             TEXT NOT NULL,       -- 'CVE' | 'GHSA' | 'DLA' | 'DSA'
    titulo              TEXT,
    descricao           TEXT,
    primary_url         TEXT,
    published_date      TIMESTAMPTZ,
    last_modified_date  TIMESTAMPTZ,
    -- Enriquecimento EPSS (LEFT JOIN -> NULL para os IDs não-CVE)
    epss_score          NUMERIC(8,6),        -- 0.033510
    epss_percentile     NUMERIC(8,6),        -- 0.883540
    epss_score_date     DATE,                -- 2026-10-08, da linha de metadados
    -- Flag derivada do LEFT JOIN ao KEV (5 esperadas a TRUE)
    em_kev              BOOLEAN NOT NULL DEFAULT FALSE
);

-- Catálogo MITRE CWE. Carrega-se o catálogo COMPLETO
-- (969 <Weakness> + 422 <Category> = 1391 linhas), não só os 147 referidos
-- pelos scans: é uma dimensão de referência.
--
-- cwe_id é INTEGER porque o XML dá o número SEM prefixo ('125', não 'CWE-125').
-- Guardar como inteiro resolve de vez o problema do prefixo, dos espaços e das
-- maiúsculas no join.
CREATE TABLE dim_cwe (
    cwe_id       INTEGER PRIMARY KEY,        -- 125
    nome         TEXT NOT NULL,
    tipo_cwe     TEXT NOT NULL,              -- 'Weakness' | 'Category'
    abstraction  TEXT,                       -- Base | Variant | Class | Pillar | Compound
    structure    TEXT,
    status       TEXT,                       -- inclui 'Deprecated' (25 casos)
    descricao    TEXT,
    CONSTRAINT chk_tipo_cwe CHECK (tipo_cwe IN ('Weakness', 'Category', 'View'))
);

-- Catálogo CISA KEV completo (1739 linhas).
-- SEM chave estrangeira para dim_cve de PROPÓSITO: 1734 destas CVE não
-- aparecem em nenhum dos scans. A ligação faz-se por LEFT JOIN nas consultas.
CREATE TABLE dim_kev (
    cve_id              TEXT PRIMARY KEY,
    vendor_project      TEXT,
    product             TEXT,
    vulnerability_name  TEXT,
    date_added          DATE,
    due_date            DATE,
    required_action     TEXT,
    known_ransomware    TEXT,                -- 'Known' (361) | 'Unknown' (1378)
    forensic_triage     TEXT,                -- 'Yes' | 'No'
    notas               TEXT
);

-- ---------------------------------------------------------------
-- FACTOS
-- ---------------------------------------------------------------

-- Uma linha por OCORRÊNCIA de vulnerabilidade: 2642 esperadas.
-- Granularidade = imagem + target + pacote + id da vulnerabilidade.
-- Esta combinação foi verificada como única nos 6 JSON (0 duplicados),
-- por isso é a chave natural e está declarada em UNIQUE.
--
-- NOTA PARA O KNIME: id_vuln é GENERATED BY DEFAULT, não ALWAYS.
-- Isso permite gerares o id no próprio workflow (nó Counter Generation) e
-- inseri-lo explicitamente. É o caminho mais simples, porque precisas do id
-- para construir a ponte_vuln_cwe — se deixasses a base de dados gerá-lo,
-- terias de o ler de volta antes de inserir a ponte.
CREATE TABLE fact_vulnerabilidade (
    id_vuln            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_imagem          INTEGER NOT NULL REFERENCES dim_imagem (id_imagem),
    cve_id             TEXT    NOT NULL REFERENCES dim_cve (cve_id),
    -- Contexto do Results[] (cada JSON tem 1 a 3 elementos em Results)
    target             TEXT NOT NULL,        -- 'nginx:1.20.0 (debian 10.9)'
    classe             TEXT,                 -- 'os-pkgs' | 'lang-pkgs'
    tipo_pacote        TEXT,                 -- debian | alpine | gobinary | jar
    -- Pacote afetado
    pkg_name           TEXT NOT NULL,
    pkg_id             TEXT,
    purl               TEXT,                 -- PkgIdentifier.PURL
    installed_version  TEXT,
    fixed_version      TEXT,                 -- NULL em 436 linhas = sem correção
    estado_correcao    TEXT,                 -- fixed | affected | will_not_fix | fix_deferred
    -- Severidade e CVSS (escolher UMA fonte, p.ex. CVSS.nvd, com fallback)
    severidade         TEXT,                 -- CRITICAL | HIGH | MEDIUM | LOW | UNKNOWN
    severity_source    TEXT,
    cvss_v3_score      NUMERIC(3,1),         -- 0.0 .. 10.0
    cvss_v3_vector     TEXT,
    cvss_v2_score      NUMERIC(3,1),
    -- Rastreio dentro da imagem
    layer_digest       TEXT,
    CONSTRAINT uq_ocorrencia UNIQUE (id_imagem, target, pkg_name, cve_id)
);

-- Relação N:N entre ocorrência e CWE.
-- Existe porque CweIDs é um ARRAY no Trivy: uma vulnerabilidade pode ter
-- 0, 1 ou 2+ CWE (257 ocorrências não têm nenhum). Depois do ungroup, cada
-- par vira uma linha aqui.
-- NÃO é coluna da tabela de factos — se fosse, duplicavas os factos.
CREATE TABLE ponte_vuln_cwe (
    id_vuln  BIGINT  NOT NULL REFERENCES fact_vulnerabilidade (id_vuln) ON DELETE CASCADE,
    cwe_id   INTEGER NOT NULL REFERENCES dim_cwe (cwe_id),
    PRIMARY KEY (id_vuln, cwe_id)
);

-- ---------------------------------------------------------------
-- ÍNDICES
-- PRIMARY KEY e UNIQUE já criam os seus. Estes cobrem os filtros e
-- joins mais prováveis nas consultas de análise.
-- ---------------------------------------------------------------
CREATE INDEX idx_fact_cve        ON fact_vulnerabilidade (cve_id);
CREATE INDEX idx_fact_imagem     ON fact_vulnerabilidade (id_imagem);
CREATE INDEX idx_fact_severidade ON fact_vulnerabilidade (severidade);
CREATE INDEX idx_fact_sem_fix    ON fact_vulnerabilidade (id_imagem)
    WHERE fixed_version IS NULL;
CREATE INDEX idx_cve_epss        ON dim_cve (epss_score DESC);
CREATE INDEX idx_cve_kev         ON dim_cve (em_kev) WHERE em_kev;
CREATE INDEX idx_ponte_cwe       ON ponte_vuln_cwe (cwe_id);

-- ---------------------------------------------------------------
-- Comentários (visíveis no DBeaver — úteis na defesa)
-- ---------------------------------------------------------------
COMMENT ON TABLE dim_imagem           IS 'Imagens Docker analisadas pelo Trivy (6)';
COMMENT ON TABLE dim_cve              IS 'Vulnerabilidades distintas + enriquecimento EPSS e flag KEV';
COMMENT ON TABLE dim_cwe              IS 'Catalogo MITRE CWE 4.20 (Weaknesses + Categories)';
COMMENT ON TABLE dim_kev              IS 'Catalogo CISA Known Exploited Vulnerabilities completo';
COMMENT ON TABLE fact_vulnerabilidade IS 'Ocorrencias de vulnerabilidade: imagem x target x pacote x CVE';
COMMENT ON TABLE ponte_vuln_cwe       IS 'Ponte N:N entre ocorrencia e CWE (CweIDs e array no Trivy)';
